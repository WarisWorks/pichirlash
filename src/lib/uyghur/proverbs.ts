/** A stable proverb for a local calendar day (YYYY-MM-DD). */
export function proverbForDay(day: string): Proverb {
  let hash = 0;
  for (const ch of day) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0;
  return proverbs[hash % proverbs.length];
}
